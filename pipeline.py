def _slugify(value: str) -> str:
    value = value.lower()
    value = re.sub(r"[^a-z0-9]+", "-", value)
    value = value.strip("-")
    return value or "video"


class ReferenceImageError(Exception):
    """Raised when a reference image is missing or cannot be retrieved."""
    pass


def validate_reference_images(
    brand_images: List[Path],
    script_data: Optional[Dict[str, Any]] = None,
    script_path: Optional[Path] = None,
) -> None:
    """Validate that all reference images exist.

    Args:
        brand_images: List of brand image paths from CLI
        script_data: Optional script data dict containing reference_images
        script_path: Optional path to script file (for resolving relative paths)

    Raises:
        ReferenceImageError: If any reference image is missing
    """
    missing = []

    # Check CLI brand images
    for img_path in brand_images:
        if not img_path.exists():
            missing.append(f"Brand image not found: {img_path}")

    # Check reference_images from script
    if script_data:
        ref_images = script_data.get("reference_images", [])
        base_dir = script_path.parent if script_path else Path.cwd()

        for ref_path in ref_images:
            # Skip GCS URIs
            if ref_path.startswith("gs://"):
                continue

            # Skip URLs (http/https)
            if ref_path.startswith("http://") or ref_path.startswith("https://"):
                # Could add URL validation here if needed
                continue

            # Resolve local path
            ref_file = Path(ref_path)
            if not ref_file.is_absolute():
                # Try multiple candidate locations
                candidates = [
                    base_dir / ref_path,
                    Path.cwd() / ref_path,
                ]
                if script_path:
                    candidates.append(script_path.parent / ref_path)

                found = False
                for candidate in candidates:
                    if candidate.exists():
                        found = True
                        break

                if not found:
                    missing.append(
                        f"Reference image not found: {ref_path}\n"
                        f"  Searched: {[str(c) for c in candidates]}"
                    )
            elif not ref_file.exists():
                missing.append(f"Reference image not found: {ref_file}")

    if missing:
        error_msg = "Missing reference images:\n" + "\n".join(f"  - {m}" for m in missing)
        raise ReferenceImageError(error_msg)


def _load_env_file(env_path: Path = Path(".env")) -> None:
    if not env_path.exists():
        return
    for line in env_path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        os.environ.setdefault(key, value)



@dataclass
class VisualSpec:
    scene_number: int
    visual_index: int
    concept_name: str
    prompt: str
    animation_prompt: str
    visual_type: str
    scene_type: str
    is_primary: bool
    duration_override: Optional[int] = None
    aspect_ratio: Optional[str] = None
    resolution_override: Optional[str] = None
    size_override: Optional[str] = None

    def combined_prompt(self) -> str:
        parts = [self.prompt.strip(), self.animation_prompt.strip()]
        return " ".join(part for part in parts if part)


def _normalize_visual_type(raw: Optional[str]) -> str:
    if not raw:
        return VISUAL_TYPE_DEFAULT
    key = str(raw).strip().lower()
    return SUPPORTED_VISUAL_TYPES.get(key, VISUAL_TYPE_DEFAULT)


def _visual_requires_image(visual_type: str) -> bool:
    return visual_type in IMAGE_REQUIRED_TYPES


def _collect_visual_specs(script: Dict[str, Any]) -> List[VisualSpec]:
    """Collect visual specifications from script.

    All visuals in a scene are processed by default (for multi-clip concatenation).
    """
    visuals: List[VisualSpec] = []
    for scene in sorted(script.get("scenes", []), key=lambda s: s.get("scene_number", 0)):
        scene_visuals = scene.get("visuals", []) or []
        for idx, visual in enumerate(scene_visuals):
            # All visuals are processed for multi-clip support
            scene_number = int(scene.get("scene_number", idx + 1))
            spec = VisualSpec(
                scene_number=scene_number,
                visual_index=idx,
                concept_name=visual.get("concept_name", f"scene{scene_number}_visual{idx+1}"),
                prompt=visual.get("prompt") or visual.get("image_prompt", ""),
                animation_prompt=visual.get("animation_prompt", ""),
                visual_type=_normalize_visual_type(visual.get("type")),
                scene_type=scene.get("scene_type", "scene"),
                is_primary=(idx == 0),
                duration_override=visual.get("duration"),
                aspect_ratio=visual.get("aspect_ratio"),
                resolution_override=visual.get("resolution"),
                size_override=visual.get("size"),
            )
            visuals.append(spec)
    return visuals


def _make_visual_filter() -> Callable[[Dict[str, Any], Dict[str, Any], int], bool]:
    """Create a filter for visuals.

    All visuals in a scene are processed by default (for multi-clip concatenation).
    """
    def _filter(scene: Dict[str, Any], visual: Dict[str, Any], index: int) -> bool:
        # All visuals are processed for multi-clip support
        return _visual_requires_image(_normalize_visual_type(visual.get("type")))

    return _filter


def _build_image_lookup(batch_data: Dict[str, Any], script_data: Optional[Dict[str, Any]] = None) -> Dict[Tuple[int, int], str]:
    lookup: Dict[Tuple[int, int], str] = {}
    visual_map = batch_data.get("visual_map") or []
    for item in visual_map:
        try:
            scene_number = int(item.get("scene_number"))
            visual_index = int(item.get("visual_index", 0))
        except (TypeError, ValueError):
            continue
        filename = item.get("filename")
        if filename:
            lookup[(scene_number, visual_index)] = filename

    if not lookup and script_data is not None:
        # Fallback for legacy batch.json files without visual_map metadata
        visuals_in_order: List[Tuple[int, int]] = []
        for scene in script_data.get("scenes", []) or []:
            scene_number = int(scene.get("scene_number", 0))
            visuals = scene.get("visuals", []) or []
            for idx, _ in enumerate(visuals):
                visuals_in_order.append((scene_number, idx))
        for (scene_number, visual_index), request in zip(visuals_in_order, batch_data.get("requests", [])):
            filename = request.get("filename")
            if filename:
                lookup[(scene_number, visual_index)] = filename
    return lookup


def _visual_output_stem(spec: VisualSpec) -> str:
    concept_slug = sanitize_filename(spec.concept_name)
    return f"scene{spec.scene_number:02d}_v{spec.visual_index + 1}_{spec.visual_type}_{concept_slug}"


async def _generate_single_video(
    job: Dict[str, Any],
    videos_dir: Path,
    model_kind: str,
    poll_sec: float,
) -> Optional[Path]:
    """Generate a single video from a job dict. Returns the output path or None on failure."""
    import aiohttp

    token = os.getenv("REPLICATE_API_TOKEN")
    if not token:
        raise EnvironmentError("REPLICATE_API_TOKEN not set.")

    # Get model based on kind
    model_owner, model_name = batch_vid.get_model_for_kind(model_kind)

    headers = {"Authorization": f"Bearer {token}"}

    async with aiohttp.ClientSession(headers=headers, timeout=aiohttp.ClientTimeout(total=None)) as session:
        sem = asyncio.Semaphore(1)
        try:
            result = await batch_vid.process_job(
                session=session,
                sem=sem,
                outdir=videos_dir,
                job=job,
                idx=1,
                poll_sec=poll_sec,
                model_owner=model_owner,
                model_name=model_name,
            )
            return result
        except Exception as exc:
            print(f"⚠️  Video generation failed: {exc}")
            return None


def _run_sequential_video_generation(
    visuals: List[VisualSpec],
    image_lookup: Dict[Tuple[int, int], str],
    images_dir: Path,
    videos_dir: Path,
    main_ref: Path,
    model_kind: str,
    seconds: int,
    resolution: Optional[str],
    poll_sec: float,
    detected_aspect: Optional[str],
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """
    Generate videos sequentially, extracting the last frame from each video
    to use as the first frame of the next video.

    Returns (jobs, metadata).
    """
    jobs: List[Dict[str, Any]] = []
    metadata: List[Dict[str, Any]] = []
    extracted_frames_dir = videos_dir.parent / "extracted_frames"
    extracted_frames_dir.mkdir(parents=True, exist_ok=True)

    main_ref_path = str(main_ref.resolve())
    previous_video_path: Optional[Path] = None

    for i, spec in enumerate(visuals):
        prompt = spec.animation_prompt.strip()
        if not prompt:
            raise ValueError(
                f"Animation prompt missing for scene {spec.scene_number} visual {spec.visual_index}."
            )

        filename = image_lookup.get((spec.scene_number, spec.visual_index))
        if not filename:
            raise FileNotFoundError(
                f"No generated image recorded for scene {spec.scene_number} visual {spec.visual_index}."
            )

        end_path = (images_dir / filename).resolve()
        if not end_path.exists():
            raise FileNotFoundError(
                f"Expected generated image not found for video job: {end_path}"
            )

        config_seconds = seconds
        if spec.duration_override is not None:
            try:
                config_seconds = int(spec.duration_override)
            except (TypeError, ValueError):
                pass

        # Determine start frame
        if i == 0 or previous_video_path is None:
            # First video: use main reference (blank image)
            start_image = main_ref_path
            print(f"[{i+1}/{len(visuals)}] First video: using main reference as start frame")
        else:
            # Extract last frame from previous video
            frame_filename = f"frame_scene{spec.scene_number:02d}_v{spec.visual_index+1}.png"
            extracted_frame_path = extracted_frames_dir / frame_filename
            print(f"[{i+1}/{len(visuals)}] Extracting last frame from previous video: {previous_video_path.name}")
            try:
                _extract_last_frame(previous_video_path, extracted_frame_path)
                start_image = str(extracted_frame_path.resolve())
                print(f"  → Extracted to: {extracted_frame_path.name}")
            except Exception as exc:
                print(f"⚠️  Failed to extract last frame: {exc}")
                print(f"  → Falling back to main reference")
                start_image = main_ref_path

        job: Dict[str, Any] = {
            "prompt": prompt,
            "first_frame_image": start_image,
            "last_frame_image": str(end_path),
            "config": {"duration": config_seconds},
            "scene_number": spec.scene_number,
            "visual_index": spec.visual_index,
            "visual_type": spec.visual_type,
            "concept_name": spec.concept_name,
        }

        chosen_aspect = spec.aspect_ratio or detected_aspect
        if chosen_aspect:
            job["config"]["aspect_ratio"] = chosen_aspect

        chosen_resolution = spec.resolution_override or resolution
        if chosen_resolution:
            job["config"]["resolution"] = chosen_resolution

        jobs.append(job)

        # Generate this video
        print(f"[{i+1}/{len(visuals)}] Generating video for scene {spec.scene_number}...")
        expected_path = _expected_video_path(job, model_kind, videos_dir)

        video_result = asyncio.run(
            _generate_single_video(job, videos_dir, model_kind, poll_sec)
        )

        if video_result and video_result.exists():
            previous_video_path = video_result
            print(f"  ✅ Generated: {video_result.name}")
        else:
            # Try expected path as fallback
            if expected_path.exists():
                previous_video_path = expected_path
                print(f"  ✅ Found at expected path: {expected_path.name}")
            else:
                print(f"  ❌ Video generation failed, no output found")
                previous_video_path = None

        abs_path = expected_path.resolve()
        metadata.append(
            {
                "scene_number": spec.scene_number,
                "visual_index": spec.visual_index,
                "visual_type": spec.visual_type,
                "concept_name": spec.concept_name,
                "prompt": spec.animation_prompt,
                "video_path": abs_path.as_posix(),
                "exists": abs_path.exists(),
                "is_primary": spec.is_primary,
                "start_frame_mode": "sequential",
                "start_frame_source": "extracted" if i > 0 and start_image != main_ref_path else "main_ref",
            }
        )

    return jobs, metadata


def _run_video_strategy(
    visuals: List[VisualSpec],
    image_lookup: Dict[Tuple[int, int], str],
    images_dir: Path,
    videos_dir: Path,
    main_ref: Path,
    model_kind: str,
    seconds: int,
    resolution: Optional[str],
    concurrency: int,
    poll_sec: float,
    start_frame_mode: str,
) -> List[Dict[str, Any]]:
    if not visuals:
        return []

    print(f"Preparing video jobs for {len(visuals)} visuals…")
    print(f"Start frame mode: {start_frame_mode}")

    # Detect aspect ratio from main_ref
    _, detected_aspect = _detect_aspect_ratio(main_ref)

    # Sequential mode: generate videos one at a time, extracting last frame from each
    if start_frame_mode == "sequential":
        print("Using sequential generation mode (extracting last frame from each video)…")
        jobs, metadata = _run_sequential_video_generation(
            visuals=visuals,
            image_lookup=image_lookup,
            images_dir=images_dir,
            videos_dir=videos_dir,
            main_ref=main_ref,
            model_kind=model_kind,
            seconds=seconds,
            resolution=resolution,
            poll_sec=poll_sec,
            detected_aspect=detected_aspect,
        )
        jobs_path = videos_dir.parent / "video_jobs.json"
        jobs_path.write_text(json.dumps(jobs, indent=2))
        print(f"Video jobs saved to {jobs_path}")

        missing = [m for m in metadata if not m["exists"]]
        if missing:
            print("⚠️  Some video jobs did not produce outputs. See visual_outputs metadata for details.")
        else:
            print("Videos generated successfully.")
        return metadata

    # Standard parallel mode (transition or reference)
    jobs = _build_video_jobs(
        visuals,
        image_lookup,
        images_dir,
        main_ref,
        seconds,
        resolution,
        detected_aspect,
        start_frame_mode=start_frame_mode,
    )

    # Calculate expected paths and filter out jobs with existing outputs
    expected_paths = [_expected_video_path(job, model_kind, videos_dir) for job in jobs]

    jobs_to_run = []
    skipped_count = 0
    for job, expected in zip(jobs, expected_paths):
        if expected.exists():
            print(f"⏭️  Skipping (already exists): {expected.name}")
            skipped_count += 1
        else:
            jobs_to_run.append(job)

    if skipped_count > 0:
        print(f"Skipped {skipped_count} existing video(s), {len(jobs_to_run)} to generate")

    # Save all jobs for reference
    jobs_path = videos_dir.parent / "video_jobs.json"
    jobs_path.write_text(json.dumps(jobs, indent=2))
    print(f"Video jobs saved to {jobs_path}")

    if jobs_to_run:
        # Write filtered jobs for batch processing
        jobs_to_run_path = videos_dir.parent / "video_jobs_pending.json"
        jobs_to_run_path.write_text(json.dumps(jobs_to_run, indent=2))

        try:
            outputs = asyncio.run(
                batch_vid.run_batch_async(
                    jobs_path=jobs_to_run_path,
                    outdir=videos_dir,
                    model_kind=model_kind,
                    max_concurrent=concurrency,
                    poll_sec=poll_sec,
                )
            )
            print(f"Video batch returned {len(outputs)} files.")
        except Exception as exc:
            print(f"⚠️  Error during video generation: {exc}")
            print("Continuing with partial results…")
    else:
        print("All videos already exist, skipping generation.")

    metadata: List[Dict[str, Any]] = []
    for spec, expected in zip(visuals, expected_paths):
        # Store absolute path to avoid path resolution issues
        abs_path = expected.resolve()
        metadata.append(
            {
                "scene_number": spec.scene_number,
                "visual_index": spec.visual_index,
                "visual_type": spec.visual_type,
                "concept_name": spec.concept_name,
                "prompt": spec.animation_prompt,
                "video_path": abs_path.as_posix(),
                "exists": abs_path.exists(),
                "is_primary": spec.is_primary,
            }
        )

    missing = [m for m in metadata if not m["exists"]]
    if missing:
        print("⚠️  Some video jobs did not produce outputs. See visual_outputs metadata for details.")
    else:
        print("Videos generated successfully.")
    return metadata


