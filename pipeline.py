def _extract_scene_audio_segments(
    original_audio: Path,
    script_data: Dict[str, Any],
    output_dir: Path,
    extension: str = "m4a",
) -> Dict[int, Path]:
    """Extract audio segments from original voice file based on scene timestamps.

    Closes gaps between scenes by extending each scene's audio to reach the next
    scene's start time. The last scene extends to the end of the audio file.

    Args:
        original_audio: Path to original voice recording
        script_data: Script with scenes containing start_time and end_time
        output_dir: Directory to write segments
        extension: Audio file extension

    Returns:
        Dict mapping scene_number to extracted audio path
    """
    audio_by_scene: Dict[int, Path] = {}
    output_dir.mkdir(parents=True, exist_ok=True)

    # Get total audio duration for extending the last scene
    total_duration = _get_audio_duration(original_audio)
    if total_duration <= 0:
        print(f"⚠️  Could not determine audio duration for {original_audio}")
        total_duration = 9999  # Fallback - ffmpeg will just read to EOF

    # Sort scenes by scene_number to properly close gaps
    scenes = sorted(script_data.get("scenes", []), key=lambda s: s.get("scene_number", 0))

    for i, scene in enumerate(scenes):
        scene_number = int(scene.get("scene_number", 0))
        start_time = scene.get("start_time", 0)
        original_end_time = scene.get("end_time", 0)

        if original_end_time <= start_time:
            print(f"⚠️  Scene {scene_number}: invalid timestamps (start={start_time}, end={original_end_time})")
            continue

        # Determine the effective end time by closing gaps:
        # - If there's a next scene, extend to its start_time
        # - If this is the last scene, extend to the total audio duration
        if i < len(scenes) - 1:
            next_scene = scenes[i + 1]
            next_start = next_scene.get("start_time", original_end_time)
            # Use the later of: original end_time or next scene's start
            effective_end_time = max(original_end_time, next_start)
        else:
            # Last scene - extend to end of audio file
            effective_end_time = max(original_end_time, total_duration)

        duration = effective_end_time - start_time
        output_path = output_dir / f"scene{scene_number:02d}.{extension}"

        # Log if we're closing a gap
        if effective_end_time > original_end_time:
            gap = effective_end_time - original_end_time
            print(f"  Scene {scene_number}: closing {gap:.2f}s gap (extending {original_end_time:.2f}s → {effective_end_time:.2f}s)")

        try:
            _extract_audio_segment(original_audio, start_time, effective_end_time, output_path)
        except Exception as exc:
            print(f"⚠️  Failed to extract audio for scene {scene_number}: {exc}")
            continue

        if output_path.exists():
            audio_by_scene[scene_number] = output_path
            print(f"  Extracted scene {scene_number} audio: {start_time:.2f}s - {effective_end_time:.2f}s ({duration:.2f}s)")

    return audio_by_scene


