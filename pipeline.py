def run_stage_videos(
    script_data: Dict[str, Any],
    batch_data: Dict[str, Any],
    images_dir: Path,
    videos_dir: Path,
    main_ref: Path,
    *,
    run_dir: Path,
    video_model: str,
    video_seconds: int,
    video_resolution: Optional[str],
    video_concurrency: int,
    poll_sec: float,
    start_frame_mode: str,
) -> List[Dict[str, Any]]:
    videos_dir.mkdir(parents=True, exist_ok=True)

    visuals = _collect_visual_specs(script_data)
    image_lookup = _build_image_lookup(batch_data, script_data)

    metadata: List[Dict[str, Any]] = []

    metadata.extend(
        _run_video_strategy(
            visuals,
            image_lookup,
            images_dir,
            videos_dir,
            main_ref,
            video_model,
            video_seconds,
            video_resolution,
            video_concurrency,
            poll_sec,
            start_frame_mode=start_frame_mode,
        )
    )

    metadata.sort(key=lambda item: (int(item.get("scene_number", 0)), int(item.get("visual_index", 0))))

    meta_path = videos_dir.parent / VIDEO_OUTPUTS_FILENAME
    meta_path.write_text(json.dumps(metadata, indent=2))
    print(f"Video output metadata saved to {meta_path}")

    # Record video cost estimate (veo with audio @ $0.15/sec) from pending jobs if available
    jobs_pending_path = videos_dir.parent / "video_jobs_pending.json"
    jobs_full_path = videos_dir.parent / "video_jobs.json"
    jobs_source = jobs_pending_path if jobs_pending_path.exists() else jobs_full_path
    try:
        jobs_data = json.loads(jobs_source.read_text()) if jobs_source.exists() else []
    except Exception:
        jobs_data = []

    if jobs_data:
        total_seconds = 0.0
        considered_jobs = 0
        for job in jobs_data:
            visual_type = job.get("visual_type", VISUAL_TYPE_DEFAULT)
            if visual_type not in {VISUAL_TYPE_DEFAULT, "video"}:
                continue  # Only bill veo-like jobs
            duration = job.get("config", {}).get("duration", 0)
            try:
                total_seconds += float(duration)
                considered_jobs += 1
            except (TypeError, ValueError):
                continue
        if total_seconds > 0:
            _record_cost_estimate(
                run_dir,
                "videos",
                total_seconds * VIDEO_SECOND_COST_USD,
                "video_generation",
                {
                    "jobs_billed": considered_jobs,
                    "total_requested_seconds": total_seconds,
                    "unit_cost_usd": VIDEO_SECOND_COST_USD,
                    "model": video_model,
                },
            )

    return metadata


def _coalesce_scene_videos(
    metadata: List[Dict[str, Any]],
    videos_dir: Path,
) -> Dict[int, Dict[int, Path]]:
    clips_by_scene: Dict[int, Dict[int, Path]] = defaultdict(dict)
    for item in metadata:
        if not item.get("exists"):
            continue
        raw_path = item.get("video_path")
        if not raw_path:
            continue
        path = Path(raw_path)
        if not path.is_absolute():
            path = (videos_dir / raw_path).resolve()
        path = path.resolve()
        if not path.exists():
            print(f"⚠️  Video file missing for scene {item.get('scene_number')}: {path}")
            continue
        try:
            scene_number = int(item.get("scene_number", 0))
            visual_index = int(item.get("visual_index", 0))
        except (TypeError, ValueError):
            continue
        clips_by_scene[scene_number][visual_index] = path
    return clips_by_scene


