@dataclass
class SceneProcessingContext:
    """Context passed to async scene processing."""
    scene_number: int
    scene_clips: Dict[int, Path]
    audio_path: Optional[Path]
    expected_visual_indices: List[int]
    image_lookup: Dict[Tuple[int, int], str]
    images_dir: Optional[Path]
    adjusted_dir: Path
    with_audio_dir: Path
    fallback_dir: Path
    audio_dir: Path
    video_buffer_ms: int
    video_length_mode: str
    veo_audio_volume: float
    using_image_fallback: bool


@dataclass
class SceneProcessingResult:
    """Result from processing a single scene."""
    scene_number: int
    combined_path: Optional[Path]
    combined_sfx_path: Optional[Path]
    meta_updates: Dict[str, Any]
    sorted_visual_indices: List[int]
    error: Optional[str] = None


async def _process_scene_async(ctx: SceneProcessingContext) -> SceneProcessingResult:
    """Process a single scene asynchronously - handles video adjustment, audio overlay, etc."""
    scene_number = ctx.scene_number
    suffix = f"scene{scene_number:02d}"

    try:
        # Handle missing audio
        if not ctx.audio_path or not ctx.audio_path.exists() or os.path.getsize(ctx.audio_path) == 0:
            print(f"⚠️  Scene {scene_number} has no narration text; generating silence.")
            silence_path = ctx.audio_dir / f"scene{scene_number:02d}_silence.mp3"
            representative_clip = min(ctx.scene_clips.values(), key=lambda p: p.stat().st_size if p.exists() else 0)
            video_duration = await _probe_duration_async(representative_clip)
            _generate_silence(video_duration, silence_path)  # Sync is fine, very fast
            audio_path = silence_path
        else:
            audio_path = ctx.audio_path

        audio_duration = await _probe_duration_async(audio_path)

        # Multi-clip concatenation: if scene has multiple clips, concatenate them first
        sorted_visual_indices = sorted(ctx.scene_clips.keys())
        sorted_clip_paths = [ctx.scene_clips[idx] for idx in sorted_visual_indices]

        if len(sorted_clip_paths) > 1:
            concat_path = ctx.adjusted_dir / f"{suffix}_concat.mp4"
            print(f"Concatenating {len(sorted_clip_paths)} clips for scene {scene_number}...")
            await _concat_videos_async(sorted_clip_paths, concat_path, reencode=True)
            working_path = concat_path
            original_clips_for_sfx = sorted_clip_paths
        else:
            working_path = sorted_clip_paths[0]
            original_clips_for_sfx = sorted_clip_paths

        video_duration = await _probe_duration_async(working_path)
        working_duration = video_duration
        speed_multiplier = 1.0

        buffer_path = ctx.adjusted_dir / f"{suffix}_buffer.mp4"
        adjusted_path = ctx.adjusted_dir / f"{suffix}_video.mp4"

        # Apply buffer adjustment to video duration
        buffer_seconds = ctx.video_buffer_ms / 1000.0
        target_video_duration = max(0.1, video_duration + buffer_seconds)

        if buffer_seconds != 0:
            print(f"{suffix}: Applying buffer adjustment of {ctx.video_buffer_ms}ms ({video_duration:.2f}s → {target_video_duration:.2f}s)")

        # If buffer is non-zero, apply it
        if abs(buffer_seconds) > DURATION_TOLERANCE:
            if buffer_seconds > 0:
                extra = buffer_seconds
                print(f"Extending {suffix} by {extra:.2f}s (buffer adjustment)")
                await _extend_video_async(working_path, extra, buffer_path)
            else:
                print(f"Trimming {suffix} by {-buffer_seconds:.2f}s (buffer adjustment)")
                await _trim_video_async(working_path, target_video_duration, buffer_path)
            working_path = buffer_path
            working_duration = target_video_duration

        # Handle audio/video reconciliation after buffer
        # audio-match: speed up audio to match video duration (default)
        # video-match: speed up video to match audio duration
        effective_audio_path = audio_path
        effective_audio_duration = audio_duration

        if audio_duration > working_duration + DURATION_TOLERANCE:
            if ctx.video_length_mode == "audio-match":
                # Speed up audio to match video duration
                audio_speed_factor = audio_duration / working_duration
                sped_up_audio_path = ctx.adjusted_dir / f"{suffix}_audio_matched.mp3"
                print(f"Audio-matching {suffix}: audio {audio_duration:.2f}s → {working_duration:.2f}s (speed {audio_speed_factor:.4f}x)")
                await asyncio.to_thread(_change_audio_speed, audio_path, audio_speed_factor, sped_up_audio_path)
                effective_audio_path = sped_up_audio_path
                effective_audio_duration = working_duration
                # No video extension needed since audio now matches video
                if working_path != adjusted_path:
                    shutil.copy2(working_path, adjusted_path)
                working_path = adjusted_path
            else:
                # video-match mode: Extend video to match audio
                extra = audio_duration - working_duration
                print(f"Extending {suffix} by {extra:.2f}s to match narration (audio: {audio_duration:.2f}s, video: {working_duration:.2f}s)")
                await _extend_video_async(working_path, extra, adjusted_path)
                working_path = adjusted_path
                working_duration = audio_duration
        elif audio_duration < working_duration - DURATION_TOLERANCE and ctx.video_length_mode == "video-match":
            speed_multiplier = working_duration / audio_duration
            print(f"Video-matching {suffix}: {working_duration:.2f}s → {audio_duration:.2f}s (speed {speed_multiplier:.4f}x)")
            await _change_video_speed_async(working_path, speed_multiplier, adjusted_path)
            working_path = adjusted_path
            # Verify actual duration after speed change
            actual_duration = await _probe_duration_async(adjusted_path)
            if actual_duration < audio_duration - DURATION_TOLERANCE:
                shortfall = audio_duration - actual_duration
                print(f"  → Extending by {shortfall:.3f}s to match audio exactly (actual: {actual_duration:.3f}s)")
                extended_path = ctx.adjusted_dir / f"{suffix}_extended.mp4"
                await _extend_video_async(adjusted_path, shortfall, extended_path)
                shutil.move(extended_path, adjusted_path)
            working_duration = audio_duration
        else:
            # No further change; ensure we have a copy in adjusted_dir
            if working_path != adjusted_path:
                shutil.copy2(working_path, adjusted_path)
            working_path = adjusted_path

        combined_path = ctx.with_audio_dir / f"{suffix}.mp4"
        combined_sfx_path = ctx.with_audio_dir / f"{suffix}_with_sfx.mp4"

        # Final safety check: ensure video is at least as long as (effective) audio to prevent cutoff
        final_adjusted_duration = await _probe_duration_async(adjusted_path)
        if final_adjusted_duration < effective_audio_duration - DURATION_TOLERANCE:
            shortfall = effective_audio_duration - final_adjusted_duration
            print(f"  → Final safety extend for {suffix}: +{shortfall:.3f}s (video: {final_adjusted_duration:.3f}s < audio: {effective_audio_duration:.3f}s)")
            safety_extended_path = ctx.adjusted_dir / f"{suffix}_safety.mp4"
            await _extend_video_async(adjusted_path, shortfall, safety_extended_path)
            shutil.move(safety_extended_path, adjusted_path)

        # Always generate narration-only version (use effective audio path which may be sped up)
        await _overlay_audio_async(adjusted_path, effective_audio_path, combined_path, pad_audio_to_video=True)

        # Generate combined audio version (Veo effects + narration)
        if ctx.using_image_fallback:
            print(f"Creating audio for {suffix}: narration only (image fallback, no Veo SFX)")
            shutil.copy2(combined_path, combined_sfx_path)
        else:
            print(f"Creating combined audio for {suffix}: Veo effects ({ctx.veo_audio_volume:.0%}) + narration (100%)")
            await _overlay_combined_audio_async(
                adjusted_path,
                effective_audio_path,
                combined_sfx_path,
                veo_audio_source=original_clips_for_sfx[0],
                narration_volume=1.0,
                video_audio_volume=ctx.veo_audio_volume,
                pad_narration=True,
            )

        # Calculate audio speed multiplier if audio was sped up
        audio_speed_multiplier = audio_duration / effective_audio_duration if effective_audio_duration != audio_duration else 1.0

        # Build metadata updates
        final_video_duration = await _probe_duration_async(adjusted_path)
        meta_updates = {
            "timing_mode": ctx.video_length_mode,
            "buffer_ms": ctx.video_buffer_ms,
            "original_audio_duration": round(audio_duration, 3),
            "effective_audio_duration": round(effective_audio_duration, 3),
            "audio_speed_multiplier": round(audio_speed_multiplier, 4),
            "original_video_duration": round(video_duration, 3),
            "adjusted_video_duration": round(final_video_duration, 3),
            "adjusted_video_path": adjusted_path.as_posix(),
            "video_speed_multiplier": round(speed_multiplier, 4),
            "combined_with_audio_path": combined_path.as_posix(),
            "combined_with_sfx_path": combined_sfx_path.as_posix(),
            "used_image_fallback": ctx.using_image_fallback,
        }
        if len(sorted_clip_paths) > 1:
            meta_updates["multi_clip_scene"] = True
            meta_updates["clip_count"] = len(sorted_clip_paths)

        return SceneProcessingResult(
            scene_number=scene_number,
            combined_path=combined_path,
            combined_sfx_path=combined_sfx_path,
            meta_updates=meta_updates,
            sorted_visual_indices=sorted_visual_indices,
        )

    except Exception as exc:
        print(f"⚠️  Error processing scene {scene_number}: {exc}")
        return SceneProcessingResult(
            scene_number=scene_number,
            combined_path=None,
            combined_sfx_path=None,
            meta_updates={},
            sorted_visual_indices=[],
            error=str(exc),
        )


async def _prepare_scene_clips_async(
    scene: Dict[str, Any],
    scene_videos: Dict[int, Dict[int, Path]],
    image_lookup: Dict[Tuple[int, int], str],
    images_dir: Optional[Path],
    audio_by_scene: Dict[int, Path],
    fallback_dir: Path,
) -> Tuple[Optional[Dict[int, Path]], bool]:
    """Prepare scene clips, creating fallbacks if needed. Returns (scene_clips, using_fallback)."""
    scene_number = int(scene.get("scene_number", 0))
    scene_clips = scene_videos.get(scene_number)
    using_image_fallback = False

    if not scene_clips:
        # Try to use static images as fallback
        if images_dir and image_lookup:
            scene_images: List[Tuple[int, Path]] = []
            for (sn, vi), filename in image_lookup.items():
                if sn == scene_number:
                    img_path = images_dir / filename
                    if img_path.exists():
                        scene_images.append((vi, img_path))

            if scene_images:
                print(f"📷 Scene {scene_number}: video missing, using static image(s) as fallback")
                using_image_fallback = True
                fallback_dir.mkdir(parents=True, exist_ok=True)

                # Get audio duration to determine image video length
                audio_path = audio_by_scene.get(scene_number)
                if audio_path and audio_path.exists():
                    fallback_duration = await _probe_duration_async(audio_path)
                else:
                    fallback_duration = 6.0

                scene_images.sort(key=lambda x: x[0])
                scene_clips = {}

                if len(scene_images) > 1:
                    per_image_duration = fallback_duration / len(scene_images)
                    # Create fallback clips in parallel
                    tasks = []
                    for vi, img_path in scene_images:
                        clip_path = fallback_dir / f"scene{scene_number:02d}_v{vi}_fallback.mp4"
                        tasks.append(_image_to_video_async(img_path, per_image_duration, clip_path))
                    await asyncio.gather(*tasks)
                    for vi, img_path in scene_images:
                        clip_path = fallback_dir / f"scene{scene_number:02d}_v{vi}_fallback.mp4"
                        scene_clips[vi] = clip_path
                        print(f"  → Created fallback clip from {img_path.name} ({per_image_duration:.2f}s)")
                else:
                    vi, img_path = scene_images[0]
                    clip_path = fallback_dir / f"scene{scene_number:02d}_fallback.mp4"
                    await _image_to_video_async(img_path, fallback_duration, clip_path)
                    scene_clips[vi] = clip_path
                    print(f"  → Created fallback clip from {img_path.name} ({fallback_duration:.2f}s)")
            else:
                return None, False
        else:
            return None, False

    # Fill in missing clips with image fallbacks
    expected_visual_indices: List[int] = []
    for (sn, vi), _ in image_lookup.items():
        if sn == scene_number:
            expected_visual_indices.append(vi)
    expected_visual_indices = sorted(set(expected_visual_indices))

    if not expected_visual_indices:
        expected_visual_indices = sorted(scene_clips.keys()) if scene_clips else [0]

    audio_path = audio_by_scene.get(scene_number)
    audio_duration_for_fallback = 6.0
    if audio_path and audio_path.exists():
        audio_duration_for_fallback = await _probe_duration_async(audio_path)

    per_clip_duration = audio_duration_for_fallback / len(expected_visual_indices) if expected_visual_indices else audio_duration_for_fallback

    fallback_tasks = []
    fallback_info = []
    for vi in expected_visual_indices:
        if vi not in scene_clips:
            img_filename = image_lookup.get((scene_number, vi))
            if img_filename and images_dir:
                img_path = images_dir / img_filename
                if img_path.exists():
                    print(f"📷 Scene {scene_number} clip {vi}: video missing, using image fallback ({img_path.name})")
                    using_image_fallback = True
                    fallback_dir.mkdir(parents=True, exist_ok=True)
                    clip_path = fallback_dir / f"scene{scene_number:02d}_v{vi}_fallback.mp4"
                    fallback_tasks.append(_image_to_video_async(img_path, per_clip_duration, clip_path))
                    fallback_info.append((vi, clip_path))

    if fallback_tasks:
        await asyncio.gather(*fallback_tasks)
        for vi, clip_path in fallback_info:
            scene_clips[vi] = clip_path

    return scene_clips, using_image_fallback


def run_stage_final(
    script_data: Dict[str, Any],
    metadata: List[Dict[str, Any]],
    videos_dir: Path,
    run_dir: Path,
    final_filename: str,
    video_buffer_ms: int = 0,
    video_length_mode: str = "audio-match",
    veo_audio_volume: float = 0.3,
    images_dir: Optional[Path] = None,
    batch_data: Optional[Dict[str, Any]] = None,
    skip_tts: bool = False,
    original_audio_path: Optional[Path] = None,
    voice: str = "Kore",
    tts_model: str = "gemini-2.5-flash-preview-tts",
    tts_concurrency: int = 3,
    images_only_mode: bool = False,
) -> None:
    base_name = final_filename.rsplit(".", 1)[0] if "." in final_filename else final_filename
    ext = final_filename.rsplit(".", 1)[1] if "." in final_filename else "mp4"

    if not metadata and not images_only_mode:
        raise RuntimeError("No video metadata available; run stage 'videos' first")

    if video_length_mode not in {"audio-match", "video-match"}:
        raise ValueError(f"Unsupported video_length_mode: {video_length_mode}")

    audio_dir = run_dir / "audio"
    audio_dir.mkdir(parents=True, exist_ok=True)

    audio_by_scene: Dict[int, Path] = {}

    if skip_tts and original_audio_path and original_audio_path.exists():
        # Voice mode with skip_tts: extract audio segments from original recording
        print(f"Extracting audio segments from original voice file: {original_audio_path}")
        audio_by_scene = _extract_scene_audio_segments(
            original_audio=original_audio_path,
            script_data=script_data,
            output_dir=audio_dir,
            extension="m4a",
        )
        print(f"Extracted {len(audio_by_scene)} scene audio segments")
    else:
        # Gemini TTS
        if not os.getenv("GOOGLE_API_KEY"):
            raise RuntimeError("GOOGLE_API_KEY must be set for TTS")

        # Import Gemini TTS module
        from tts.gemini_tts import synthesize_narration as gemini_synthesize

        print(f"Generating TTS narration (voice: {voice}, model: {tts_model})...")
        tts_results = gemini_synthesize(
            script_data=script_data,
            output_dir=audio_dir,
            voice_name=voice,
            model=tts_model,
            concurrency=tts_concurrency,
            output_format="mp3",
        )

        tts_cost_total = 0.0

        for audio_path, meta_path in tts_results:
            scene_num_str = audio_path.stem.replace("scene", "")
            audio_by_scene[int(scene_num_str)] = audio_path
            try:
                meta_data = json.loads(meta_path.read_text())
                usage = meta_data.get("usage")
                cost = _extract_cost_from_usage(usage)
                if cost is not None:
                    tts_cost_total += cost
            except Exception:
                pass

        if tts_cost_total > 0:
            _record_cost_estimate(
                run_dir,
                "tts",
                tts_cost_total,
                "gemini_tts",
                {"model": tts_model, "scenes": len(tts_results)},
            )

    scene_videos = _coalesce_scene_videos(metadata, videos_dir)
    meta_lookup: Dict[Tuple[int, int], Dict[str, Any]] = {}
    for item in metadata:
        try:
            key = (int(item.get("scene_number", 0)), int(item.get("visual_index", 0)))
            meta_lookup[key] = item
        except (TypeError, ValueError):
            continue

    # Build image lookup for fallback when videos are missing
    image_lookup: Dict[Tuple[int, int], str] = {}
    if images_dir and batch_data:
        image_lookup = _build_image_lookup(batch_data, script_data)

    def _generate_images_only_final() -> Optional[Path]:
        """Create an images-only final video using static images + narration."""
        if not (images_dir and batch_data):
            print("ℹ️  Skipping images-only video (images_dir or batch_data not provided).")
            return None

        print("Generating images-only video (static images + narration)…")
        images_video_dir = run_dir / "videos_images_only"
        images_video_dir.mkdir(parents=True, exist_ok=True)

        async def _process_images_only_scene(scene: Dict[str, Any]) -> Optional[Tuple[int, Path]]:
            """Process a single scene for images-only version."""
            scene_number = int(scene.get("scene_number", 0))
            audio_path = audio_by_scene.get(scene_number)
            if not audio_path or not audio_path.exists():
                print(f"⚠️  Skipping scene {scene_number} for images-only: no audio found.")
                return None

            # Get ALL images for this scene (multi-clip support)
            scene_images: List[Tuple[int, str]] = []
            for (sn, vi), filename in image_lookup.items():
                if sn == scene_number:
                    scene_images.append((vi, filename))
            scene_images.sort(key=lambda x: x[0])

            if not scene_images:
                print(f"⚠️  Skipping scene {scene_number} for images-only: no images found.")
                return None

            # Validate images and create clips
            valid_images = []
            for vi, filename in scene_images:
                img_path = images_dir / filename
                if not img_path.exists():
                    print(f"⚠️  Scene {scene_number} clip {vi}: image missing ({filename})")
                    continue
                valid_images.append((vi, img_path))

            if not valid_images:
                print(f"⚠️  Skipping scene {scene_number} for images-only: no valid image files.")
                return None

            audio_duration = await _probe_duration_async(audio_path)

            if len(valid_images) > 1:
                per_image_duration = audio_duration / len(valid_images)
                clip_tasks = []
                image_clip_paths = []
                for vi, img_path in valid_images:
                    clip_path = images_video_dir / f"scene{scene_number:02d}_v{vi+1}_clip.mp4"
                    clip_tasks.append(_image_to_video_async(img_path, per_image_duration, clip_path))
                    image_clip_paths.append(clip_path)

                await asyncio.gather(*clip_tasks)
                for vi, img_path in valid_images:
                    print(f"  ✓ Scene {scene_number} clip {vi+1}: {img_path.name} ({per_image_duration:.2f}s)")

                # Concatenate all image clips
                concat_path = images_video_dir / f"scene{scene_number:02d}_concat.mp4"
                await _concat_videos_async(image_clip_paths, concat_path, reencode=True)
                image_video_path = concat_path
            else:
                # Single image: create video from it
                _, img_path = valid_images[0]
                image_video_path = images_video_dir / f"scene{scene_number:02d}_video.mp4"
                await _image_to_video_async(img_path, audio_duration, image_video_path)
                print(f"  ✓ Scene {scene_number}: {img_path.name} ({audio_duration:.2f}s)")

            # Overlay audio on the (potentially concatenated) video
            image_with_audio_path = images_video_dir / f"scene{scene_number:02d}.mp4"
            await _overlay_audio_async(image_video_path, audio_path, image_with_audio_path, pad_audio_to_video=False)

            return (scene_number, image_with_audio_path)

        async def _process_all_images_only() -> List[Path]:
            """Process all scenes for images-only version sequentially to avoid memory issues."""
            scenes = sorted(script_data.get("scenes", []), key=lambda s: s.get("scene_number", 0))
            results: List[Optional[Tuple[int, Path]]] = []

            for scene in scenes:
                result = await _process_images_only_scene(scene)
                results.append(result)

            # Filter out None results and sort by scene number
            valid_results = [(sn, path) for r in results if r is not None for sn, path in [r]]
            valid_results.sort(key=lambda x: x[0])
            return [path for _, path in valid_results]

        # Reset event loop to avoid issues with subprocess pipes from prior asyncio.run() calls
        asyncio.set_event_loop(asyncio.new_event_loop())
        final_clips_images = asyncio.run(_process_all_images_only())

        if final_clips_images:
            final_dir = run_dir / "final"
            final_dir.mkdir(parents=True, exist_ok=True)
            final_images_only_path = final_dir / f"{base_name}_images_only.{ext}"
            print("Concatenating images-only scenes…")
            _concat_videos(final_clips_images, final_images_only_path, reencode=True)
            print(f"Images-only video saved to {final_images_only_path}")
            return final_images_only_path

        print("⚠️  No images-only clips were produced; skipping images-only final video.")
        return None

    if images_only_mode:
        _generate_images_only_final()
        return

    adjusted_dir = run_dir / "videos_adjusted"
    adjusted_dir.mkdir(parents=True, exist_ok=True)
    with_audio_dir = run_dir / "videos_with_audio"
    with_audio_dir.mkdir(parents=True, exist_ok=True)
    fallback_dir = run_dir / "videos_fallback"

    # =========================================================================
    # PARALLEL SCENE PROCESSING
    # Process all scenes concurrently for significant speedup
    # =========================================================================

    async def _process_all_scenes_async() -> Tuple[List[Path], List[Path]]:
        """Process all scenes in parallel and return final clips."""
        scenes = sorted(script_data.get("scenes", []), key=lambda s: s.get("scene_number", 0))
        print(f"Processing {len(scenes)} scenes in parallel...")

        # Phase 1: Prepare all scene clips (including fallbacks) in parallel
        prep_tasks = []
        for scene in scenes:
            prep_tasks.append(_prepare_scene_clips_async(
                scene=scene,
                scene_videos=scene_videos,
                image_lookup=image_lookup,
                images_dir=images_dir,
                audio_by_scene=audio_by_scene,
                fallback_dir=fallback_dir,
            ))

        prep_results = await asyncio.gather(*prep_tasks)

        # Build contexts for scenes that have clips
        contexts: List[SceneProcessingContext] = []
        for scene, (scene_clips_result, using_fallback) in zip(scenes, prep_results):
            scene_number = int(scene.get("scene_number", 0))

            if not scene_clips_result:
                print(f"⚠️  Skipping scene {scene_number}: no video or image clips available.")
                continue

            # Get expected visual indices
            expected_visual_indices: List[int] = []
            for (sn, vi), _ in image_lookup.items():
                if sn == scene_number:
                    expected_visual_indices.append(vi)
            expected_visual_indices = sorted(set(expected_visual_indices))
            if not expected_visual_indices:
                expected_visual_indices = sorted(scene_clips_result.keys()) if scene_clips_result else [0]

            ctx = SceneProcessingContext(
                scene_number=scene_number,
                scene_clips=scene_clips_result,
                audio_path=audio_by_scene.get(scene_number),
                expected_visual_indices=expected_visual_indices,
                image_lookup=image_lookup,
                images_dir=images_dir,
                adjusted_dir=adjusted_dir,
                with_audio_dir=with_audio_dir,
                fallback_dir=fallback_dir,
                audio_dir=audio_dir,
                video_buffer_ms=video_buffer_ms,
                video_length_mode=video_length_mode,
                veo_audio_volume=veo_audio_volume,
                using_image_fallback=using_fallback,
            )
            contexts.append(ctx)

        if not contexts:
            return [], []

        # Phase 2: Process all scenes in parallel
        process_tasks = [_process_scene_async(ctx) for ctx in contexts]
        results: List[SceneProcessingResult] = await asyncio.gather(*process_tasks)

        # Collect results and update metadata
        final_clips_list: List[Tuple[int, Path]] = []
        final_clips_sfx_list: List[Tuple[int, Path]] = []

        for result in results:
            if result.error:
                print(f"⚠️  Scene {result.scene_number} failed: {result.error}")
                continue

            if result.combined_path and result.combined_sfx_path:
                final_clips_list.append((result.scene_number, result.combined_path))
                final_clips_sfx_list.append((result.scene_number, result.combined_sfx_path))

                # Update metadata
                for visual_index in result.sorted_visual_indices:
                    meta_entry = meta_lookup.get((result.scene_number, visual_index))
                    if meta_entry is not None:
                        meta_entry.update(result.meta_updates)

        # Sort by scene number to ensure correct order
        final_clips_list.sort(key=lambda x: x[0])
        final_clips_sfx_list.sort(key=lambda x: x[0])

        return (
            [p for _, p in final_clips_list],
            [p for _, p in final_clips_sfx_list],
        )

    # Run the async scene processing
    # Reset event loop to avoid issues with subprocess pipes from prior asyncio.run() calls
    # (e.g., from gemini_tts which uses its own asyncio.run internally)
    asyncio.set_event_loop(asyncio.new_event_loop())
    final_clips, final_clips_sfx = asyncio.run(_process_all_scenes_async())

    if not final_clips:
        raise RuntimeError("No scene clips with audio were produced; final video cannot be created")

    final_dir = run_dir / "final"
    final_dir.mkdir(parents=True, exist_ok=True)

    # Generate narration-only final video
    final_path = final_dir / final_filename
    print("Concatenating scenes into final video (narration only)…")
    _concat_videos(final_clips, final_path, reencode=True)
    print(f"Final video saved to {final_path}")

    # Generate combined audio final video (with Veo sound effects)
    final_sfx_path = final_dir / f"{base_name}_with_sfx.{ext}"
    print("Concatenating scenes into final video (with sound effects)…")
    _concat_videos(final_clips_sfx, final_sfx_path, reencode=True)
    print(f"Final video with sound effects saved to {final_sfx_path}")

    # Generate images-only version (static images + audio, no Veo animation)
    _generate_images_only_final()

    # Persist updated metadata with adjustment details
    meta_path = run_dir / VIDEO_OUTPUTS_FILENAME
    try:
        meta_path.write_text(json.dumps(metadata, indent=2))
    except Exception as exc:
        print(f"⚠️  Failed to write updated metadata to {meta_path}: {exc}")


