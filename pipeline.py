def _build_video_jobs(
    visuals: List[VisualSpec],
    image_lookup: Dict[Tuple[int, int], str],
    images_dir: Path,
    main_ref: Path,
    seconds: int,
    resolution: Optional[str],
    aspect_ratio: Optional[str] = None,
    start_frame_mode: str = "transition",
) -> List[Dict[str, Any]]:
    jobs: List[Dict[str, Any]] = []
    main_ref_path = str(main_ref.resolve())
    previous_end: Optional[str] = None

    for spec in visuals:
        prompt = spec.animation_prompt.strip()
        if not prompt:
            raise ValueError(
                f"Animation prompt missing for scene {spec.scene_number} visual {spec.visual_index}."
            )

        filename = image_lookup.get((spec.scene_number, spec.visual_index))
        if not filename:
            raise FileNotFoundError(
                f"No generated image recorded for scene {spec.scene_number} visual {spec.visual_index}."
            )

        end_path = (images_dir / filename).resolve()
        if not end_path.exists():
            raise FileNotFoundError(
                f"Expected generated image not found for video job: {end_path}"
            )

        config_seconds = seconds
        if spec.duration_override is not None:
            try:
                config_seconds = int(spec.duration_override)
            except (TypeError, ValueError):
                pass

        # Animate mode: use generated image as start frame only (no end frame)
        if start_frame_mode == "animate":
            start_image = str(end_path)
            end_image = None
        elif start_frame_mode == "transition" and previous_end:
            start_image = previous_end
            end_image = str(end_path)
        else:
            start_image = main_ref_path
            end_image = str(end_path)

        job: Dict[str, Any] = {
            "prompt": prompt,
            "first_frame_image": start_image,
            "config": {"duration": config_seconds},
            "scene_number": spec.scene_number,
            "visual_index": spec.visual_index,
            "visual_type": spec.visual_type,
            "concept_name": spec.concept_name,
        }
        if end_image:
            job["last_frame_image"] = end_image

        # Add aspect ratio if provided
        chosen_aspect = spec.aspect_ratio or aspect_ratio
        if chosen_aspect:
            job["config"]["aspect_ratio"] = chosen_aspect

        chosen_resolution = spec.resolution_override or resolution
        if chosen_resolution:
            job["config"]["resolution"] = chosen_resolution

        jobs.append(job)
        previous_end = str(end_path)
    return jobs


