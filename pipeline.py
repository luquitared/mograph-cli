TTS_NORMALIZATION_METRICS_FILENAME = "tts_normalization_metrics.json"


def _normalize_audio_to_target(
    audio_path: Path,
    target_seconds: float,
    run_dir: Path,
    voice_name: str,
    word_count: int,
) -> Tuple[Path, Dict[str, Any]]:
    """Normalize audio duration to match target seconds.

    Time-stretches the audio to match the target duration and logs metrics.

    Args:
        audio_path: Path to the original TTS audio
        target_seconds: Target duration in seconds
        run_dir: Run directory for saving normalized audio and metrics
        voice_name: Name of the voice used for TTS
        word_count: Number of words in the narration

    Returns:
        Tuple of (normalized_audio_path, metrics_dict)
    """
    actual_duration = _get_audio_duration(audio_path)
    deviation = actual_duration - target_seconds
    deviation_pct = (deviation / target_seconds) * 100
    speed_factor = actual_duration / target_seconds
    actual_wps = word_count / actual_duration if actual_duration > 0 else 0
    target_wps = word_count / target_seconds if target_seconds > 0 else 0

    metrics = {
        "voice": voice_name,
        "word_count": word_count,
        "target_seconds": target_seconds,
        "actual_seconds": round(actual_duration, 3),
        "deviation_seconds": round(deviation, 3),
        "deviation_percent": round(deviation_pct, 2),
        "speed_factor_applied": round(speed_factor, 4),
        "actual_wps": round(actual_wps, 3),
        "target_wps": round(target_wps, 3),
        "normalized": True,
        "timestamp": datetime.now().isoformat(),
    }

    # Apply time-stretching
    audio_dir = audio_path.parent
    normalized_path = audio_dir / "combined_tts_normalized.mp3"

    print(f"Normalizing audio: {actual_duration:.2f}s → {target_seconds:.2f}s (speed factor: {speed_factor:.4f}x)")

    _change_audio_speed(audio_path, speed_factor, normalized_path)

    # Verify the result
    normalized_duration = _get_audio_duration(normalized_path)
    metrics["normalized_duration"] = round(normalized_duration, 3)
    metrics["normalization_error"] = round(abs(normalized_duration - target_seconds), 3)

    print(f"Normalized audio duration: {normalized_duration:.2f}s (target: {target_seconds}s, error: {metrics['normalization_error']:.3f}s)")

    # Save metrics
    metrics_path = run_dir / TTS_NORMALIZATION_METRICS_FILENAME
    metrics_path.write_text(json.dumps(metrics, indent=2))
    print(f"TTS normalization metrics saved to {metrics_path}")

    return normalized_path, metrics


