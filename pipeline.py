def _load_metrics(run_dir: Path) -> Dict[str, Any]:
    """Load existing metrics or return empty structure."""
    metrics_path = run_dir / METRICS_FILENAME
    if metrics_path.exists():
        metrics = json.loads(metrics_path.read_text())
        if "costs" not in metrics:
            metrics["costs"] = {"total_usd": 0.0, "items": [], "by_category": {}}
        else:
            metrics["costs"].setdefault("items", [])
            metrics["costs"].setdefault("by_category", {})
            metrics["costs"].setdefault("total_usd", 0.0)
        return metrics
    return {
        "run_started_at": None,
        "run_ended_at": None,
        "total_duration_seconds": None,
        "stages": {},
        "costs": {
            "total_usd": 0.0,
            "items": [],
            "by_category": {},
        },
    }


def _save_metrics(run_dir: Path, metrics: Dict[str, Any]) -> None:
    """Save metrics to JSON file."""
    (run_dir / METRICS_FILENAME).write_text(json.dumps(metrics, indent=2))


def _ensure_costs(metrics: Dict[str, Any]) -> None:
    """Ensure costs structure exists on metrics."""
    if "costs" not in metrics:
        metrics["costs"] = {"total_usd": 0.0, "items": [], "by_category": {}}
    metrics["costs"].setdefault("items", [])
    metrics["costs"].setdefault("by_category", {})
    metrics["costs"].setdefault("total_usd", 0.0)


def _record_cost(run_dir: Path, category: str, amount_usd: float, details: Dict[str, Any]) -> None:
    """Record a cost entry in run metrics."""
    metrics = _load_metrics(run_dir)
    _ensure_costs(metrics)

    entry = {
        "category": category,
        "amount_usd": round(float(amount_usd), 4),
        "details": details,
        "timestamp": datetime.now().isoformat(),
    }
    metrics["costs"]["items"].append(entry)
    metrics["costs"]["total_usd"] = round(metrics["costs"]["total_usd"] + float(amount_usd), 4)
    metrics["costs"]["by_category"][category] = round(
        metrics["costs"]["by_category"].get(category, 0.0) + float(amount_usd), 4
    )
    _save_metrics(run_dir, metrics)


def _extract_cost_from_usage(usage: Any) -> Optional[float]:
    """Best-effort extraction of cost from usage metadata."""
    if not usage:
        return None
    if hasattr(usage, "model_dump"):
        usage = usage.model_dump()
    if not isinstance(usage, dict):
        return None
    for key in ("total_cost", "cost", "estimated_cost"):
        if key in usage:
            try:
                return float(usage[key])
            except (TypeError, ValueError):
                continue
    return None


def _record_llm_cost_from_result(run_dir: Path, result: Dict[str, Any], label: str) -> None:
    """Log LLM cost if usage metadata is present on an API result."""
    usage = result.get("_api_usage")
    cost = _extract_cost_from_usage(usage)
